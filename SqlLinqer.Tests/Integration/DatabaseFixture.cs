using System.Data;
using System.Data.Common;
using MySql.Data.MySqlClient;
using Npgsql;
using SqlLinqer;
using SqlLinqer.Connections;
using SqlLinqer.Extensions.StringExtensions;
using SqlLinqer.Modeling;

namespace SqlLinqer.Tests.Integration;

internal sealed class DatabaseFixture
{
    private readonly Func<DbConnection> _createConnection;
    internal DbFlavor Flavor { get; }
    internal BaseConnector Connector { get; }
    internal string Q(string name) => name.DbWrap(Flavor);
    internal static readonly DateTime SampleDate = new(2025, 6, 15, 13, 14, 15, DateTimeKind.Unspecified);

    internal DatabaseFixture(DbFlavor flavor, string connectionString)
    {
        Flavor = flavor;
        var parsed = new DbConnectionStringBuilder { ConnectionString = connectionString };
        if (!parsed.TryGetValue("Database", out object database) || !database.ToString().StartsWith("sqllinqer_integration_", StringComparison.Ordinal))
            throw new ArgumentException("Integration tests require a disposable database named sqllinqer_integration_<run id>.");

        _createConnection = flavor == DbFlavor.PostgreSql
            ? () => new NpgsqlConnection(connectionString)
            : () => new MySqlConnection(connectionString);
        using var example = _createConnection();
        Connector = new ReplicatorConnector(example, flavor, new ConnectorOptions
        {
            ConnectionTimeout = TimeSpan.FromSeconds(3),
            CommandTimeout = TimeSpan.FromSeconds(15),
        });
    }

    internal DbConnection Open()
    {
        var connection = _createConnection();
        try { connection.Open(); return connection; }
        catch { connection.Dispose(); throw; }
    }

    internal void WaitUntilReady()
    {
        var timer = System.Diagnostics.Stopwatch.StartNew();
        Exception lastError = null;
        while (timer.Elapsed < TimeSpan.FromSeconds(90))
        {
            try { using var connection = Open(); return; }
            catch (DbException error) { lastError = error; Thread.Sleep(500); }
        }
        throw new InvalidOperationException($"{Flavor} did not become ready within 90 seconds.", lastError);
    }

    internal void Execute(string sql)
    {
        using var connection = Open();
        using var command = connection.CreateCommand();
        command.CommandTimeout = 15;
        command.CommandText = sql;
        command.ExecuteNonQuery();
    }

    internal long Count()
    {
        using var connection = Open();
        using var command = connection.CreateCommand();
        command.CommandText = $"SELECT COUNT(*) FROM {Q("it_items")}";
        return Convert.ToInt64(command.ExecuteScalar());
    }

    internal string ReadName(int id)
    {
        using var connection = Open();
        using var command = connection.CreateCommand();
        command.CommandText = $"SELECT {Q("name")} FROM {Q("it_items")} WHERE {Q("id")} = @id";
        var parameter = command.CreateParameter(); parameter.ParameterName = "@id"; parameter.Value = id;
        command.Parameters.Add(parameter);
        return command.ExecuteScalar() as string;
    }

    internal void Reset()
    {
        Execute($"DROP TABLE IF EXISTS {Q("it_children")}; DROP TABLE IF EXISTS {Q("it_items")}; DROP TABLE IF EXISTS {Q("it_categories")};");
        string identity = Flavor == DbFlavor.PostgreSql ? "INTEGER GENERATED BY DEFAULT AS IDENTITY" : "INTEGER AUTO_INCREMENT";
        string timestamp = Flavor == DbFlavor.PostgreSql ? "TIMESTAMP(6)" : "DATETIME(6)";
        Execute($"""
            CREATE TABLE {Q("it_categories")} ({Q("id")} INTEGER PRIMARY KEY, {Q("name")} VARCHAR(64) NOT NULL);
            CREATE TABLE {Q("it_items")} (
                {Q("id")} {identity} PRIMARY KEY,
                {Q("name")} VARCHAR(128) NOT NULL,
                {Q("enabled")} BOOLEAN NOT NULL,
                {Q("happened_at")} {timestamp} NULL,
                {Q("category_id")} INTEGER NULL,
                {Q("state")} VARCHAR(16) NOT NULL DEFAULT 'Active');
            CREATE TABLE {Q("it_children")} ({Q("id")} INTEGER PRIMARY KEY, {Q("item_id")} INTEGER NOT NULL, {Q("name")} VARCHAR(64) NOT NULL);
            INSERT INTO {Q("it_categories")} VALUES (1, 'engineering'), (2, 'sales');
            INSERT INTO {Q("it_children")} VALUES (1, 1, 'child one'), (2, 1, 'child two'), (3, 2, 'child three');
            """);
        using var connection = Open();
        for (int i = 1; i <= 22; i++)
        {
            using var command = connection.CreateCommand();
            command.CommandText = $"INSERT INTO {Q("it_items")} ({Q("id")}, {Q("name")}, {Q("enabled")}, {Q("happened_at")}, {Q("category_id")}) VALUES (@id, @name, @enabled, @when, @category)";
            Add(command, "@id", i);
            Add(command, "@name", "Item " + i);
            Add(command, "@enabled", i % 2 == 1);
            Add(command, "@when", i % 2 == 1 ? SampleDate.AddTicks(1234560) : null, DbType.DateTime);
            Add(command, "@category", i == 3 ? null : i % 2 == 1 ? 1 : 2, DbType.Int32);
            command.ExecuteNonQuery();
        }
        if (Flavor == DbFlavor.PostgreSql)
            Execute("SELECT setval(pg_get_serial_sequence('it_items', 'id'), 22, true)");
    }

    private static void Add(DbCommand command, string name, object value, DbType? nullType = null)
    {
        var parameter = command.CreateParameter();
        parameter.ParameterName = name;
        parameter.Value = value ?? DBNull.Value;
        if (value == null && nullType.HasValue) parameter.DbType = nullType.Value;
        command.Parameters.Add(parameter);
    }
}

[SqlTable("it_items"), SqlAutoInsert]
internal sealed class IntegrationItem : SqlLinqerPrimaryKeyObject<IntegrationItem, int>
{
    private IntegrationItem() { LoadedViaPrivateConstructor = true; }
    internal IntegrationItem(string name, bool enabled, int? categoryId, DateTime? happenedAt)
    {
        Name = name; Enabled = enabled; CategoryId = categoryId; HappenedAt = happenedAt;
    }
    [SqlPrimaryKey, SqlColumn("id")] public int Id { get; private set; }
    [SqlColumn("name")] public string Name { get; private set; }
    [SqlColumn("enabled")] public bool Enabled;
    [SqlColumn("happened_at")] public DateTime? HappenedAt { get; private set; }
    [SqlColumn("category_id")] public int? CategoryId { get; private set; }
    [SqlColumn("state"), SqlAutoInsertExclude] public IntegrationState State { get; private set; }
    [SqlOneToOne(nameof(CategoryId))] public IntegrationCategory Category { get; }
    [SqlOneToMany(nameof(IntegrationChild.ItemId))] public IEnumerable<IntegrationChild> Children { get; private set; }
    [SqlIgnore] public bool LoadedViaPrivateConstructor { get; }
}

internal enum IntegrationState { Active, Inactive }

[SqlTable("it_categories")]
internal sealed class IntegrationCategory
{
    [SqlPrimaryKey, SqlColumn("id")] public int Id { get; set; }
    [SqlColumn("name")] public string Name = null;
}

[SqlTable("it_children")]
internal sealed class IntegrationChild
{
    [SqlPrimaryKey, SqlColumn("id")] public int Id { get; set; }
    [SqlColumn("item_id")] public int ItemId { get; set; }
    [SqlColumn("name")] public string Name { get; set; }
}
